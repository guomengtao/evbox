/** 公历日期 → Julian Day Number（同一天恒定，用于确定性取句） */
function dayIndex(date) {
  var d = date || new Date()
  var y = d.getFullYear()
  var m = d.getMonth() + 1
  var day = d.getDate()
  var a = Math.floor((14 - m) / 12)
  var y2 = y + 4800 - a
  var m2 = m + 12 * a - 3
  return (
    day +
    Math.floor((153 * m2 + 2) / 5) +
    365 * y2 +
    Math.floor(y2 / 4) -
    Math.floor(y2 / 100) +
    Math.floor(y2 / 400) -
    32045
  )
}

/**
 * 取当日一句
 * @param {Date} date 基准日期，缺省今天
 * @param {number} offset 手动偏移（「换一句」时 +1）
 */
function quoteOfDay(date, offset) {
  var i = dayIndex(date) + (offset || 0)
  var len = QUOTES.length
  var idx = ((i % len) + len) % len
  return QUOTES[idx]
}

/** 形如「9月26日」 */
function dateText(date) {
  var d = date || new Date()
  return d.getMonth() + 1 + "月" + d.getDate() + "日"
}

